export function lessonMoves(lesson: OpeningLesson, branch: OpeningBranch) {
  return `${lesson.setup} ${lesson[branch]}`.trim().split(/\s+/);
}

export function setupLength(lesson: OpeningLesson) {
  return lesson.setup.trim().split(/\s+/).length;
}

export function lessonPositions(
  lesson: OpeningLesson,
  branch: OpeningBranch = "trap",
) {
  const game = new Chess();
  const snapshot = (move?: ReturnType<Chess["move"]>) => ({
    fen: game.fen(),
    position: positionOf(game),
    move,
    checkmate: game.isCheckmate(),
    checkedKing: game.inCheck()
      ? game
          .board()
          .flat()
          .find((piece) => piece?.type === "k" && piece.color === game.turn())
          ?.square
      : undefined,
  });
  const positions = [snapshot()];
  for (const san of lessonMoves(lesson, branch))
    positions.push(snapshot(game.move(san)));
  return positions;
}
